"""Write wiki/lua_variable_names.md from the decompiler's variable list.

The decompile_scripts stage (tools/int2lua.py) writes data/scripts/variable_names.tsv:
every global, map and local variable each script uses, its name and where the name
comes from. That file is derived from the install and stays local; this page keeps
only what is worth checking by hand, for the scripts the game uses (scripts.lst):
the inferred names and the variables that stay numbers.

    python tools/variable_review.py [data/scripts/variable_names.tsv] [wiki/lua_variable_names.md]

Regenerate it after a change to int2lua's naming.
"""

import csv
import datetime
import json
import os
import sys

KIND = {"gvar": "GVAR", "mvar": "MVAR", "lvar": "LVAR"}


def listed_scripts(path=os.path.join("lut", "lst", "scripts.json")):
    with open(path, encoding="utf-8") as fh:
        return set(x.split(".")[0].strip().lower() for x in json.load(fh))


def cell(text):
    return text.replace("|", "\\|")


def main(argv):
    src = argv[1] if len(argv) > 1 else os.path.join("data", "scripts", "variable_names.tsv")
    out = argv[2] if len(argv) > 2 else os.path.join("wiki", "lua_variable_names.md")
    with open(src, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    listed = listed_scripts()
    rows = [r for r in rows if r["script"] in listed]
    named = [r for r in rows if r["name"] and not r["inferred"]]
    inferred = [r for r in rows if r["inferred"]]
    numbers = [r for r in rows if not r["name"]]

    w = []
    w.append("# Lua script variable names — review list")
    w.append("")
    w.append("> Generated by `tools/variable_review.py` from `data/scripts/variable_names.tsv` (written by the")
    w.append("> `decompile_scripts` stage, `tools/int2lua.py`) on %s. Regenerate it after a change to the" % datetime.date.today().isoformat())
    w.append("> decompiler's naming. See [lua_scripts.md](lua_scripts.md) (names) and [known_bugs.md](known_bugs.md) L3.")
    w.append("")
    w.append("Each row is one variable one script uses (scripts in scripts.lst only). The full list, with every")
    w.append("name and its source, is the local `data/scripts/variable_names.tsv`; it is derived from the install")
    w.append("and Black Isle's sources and not committed. This page keeps what is worth checking by hand:")
    w.append("")
    w.append("| | Variables |")
    w.append("|---|---|")
    w.append("| Named from a source (`vault13.gam`, `maps/<map>.gam`, the script's `.ssl`) | %d |" % len(named))
    w.append("| Inferred (below) | %d |" % len(inferred))
    w.append("| Still numbers (below) | %d |" % len(numbers))
    w.append("")
    w.append("## Inferred names")
    w.append("")
    w.append("Marked `-- inferred: <why>` where the script's Lua declares them. Kinds: an `.ssl` that lacks a few")
    w.append("of the `.int`'s procedures (another version of the same script), a global variable used as the base")
    w.append("of an index expression, and an operand the compiler left out, restored from the source.")
    w.append("")
    w.append("| Script | Kind | Number | Name | Source |")
    w.append("|---|---|---|---|---|")
    for r in sorted(inferred, key=lambda r: (r["script"], r["kind"], int(r["number"]))):
        w.append("| %s | %s | %s | `%s` | %s |" % (r["script"], KIND[r["kind"]], r["number"], r["name"], cell(r["source"])))
    w.append("")
    w.append("## Still numbers")
    w.append("")
    w.append("No source names these: the script's `.ssl` uses the bare number, `vault13.gam` has no entry for it,")
    w.append("or no `.ssl` exists for the script. LVAR -1 is a generic macro's \"no variable\" argument; the code")
    w.append("using it sits behind `if -1 > -1` and never runs (the Broken Hills `bc*` scripts).")
    w.append("")
    w.append("| Script | Kind | Number | Why |")
    w.append("|---|---|---|---|")
    for r in sorted(numbers, key=lambda r: (r["script"], r["kind"], int(r["number"]))):
        w.append("| %s | %s | %s | %s |" % (r["script"], KIND[r["kind"]], r["number"], cell(r["source"])))
    w.append("")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(w))
    print("%s: %d named, %d inferred, %d numbers" % (out, len(named), len(inferred), len(numbers)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
